#!/usr/bin/env python3
"""Export the Otter design masters (design/source-assets/) into Android runtime resources.

Deterministic and idempotent: the same masters always produce the same pixels.

  python3 scripts/export-assets.py           # verify masters, (re)write all outputs, print sizes
  python3 scripts/export-assets.py --check   # verify masters + that every output is present and up to date

Rules (otter-assets/README_AGENT.md, README_M3_ADDITIONS.md, M3 plan Task 3):
  * masters are never modified; their SHA-256 must match manifest.json and manifest.m3-additions.json
  * illustrations / family avatar: alpha < 16 -> 0, alpha >= 250 -> 255 (removes the faint halo), no trimming,
    premultiplied LANCZOS resize, lossless WebP with alpha into core/ui drawable-nodpi
  * launcher foreground: full canvas (already safe-zone padded, never trimmed or shrunk again) -> mipmap PNGs
  * monochrome launcher layer: VectorDrawable built from the SVG, path data copied verbatim
  * notification icon (M5, D62): the same head path, viewport cropped to its bounds, 24 dp
"""
import argparse
import hashlib
import io
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "source-assets"
UI_RES = ROOT / "core" / "ui" / "src" / "main" / "res"
APP_RES = ROOT / "app" / "src" / "main" / "res"

ILLUSTRATIONS = {  # master -> (runtime name, px)
    "otter_welcome.png": ("otter_welcome", 880),
    "otter_empty_chat.png": ("otter_empty_chat", 880),
    "otter_m3_no_chats.png": ("otter_no_chats", 880),
    "otter_family_avatar.png": ("otter_family_avatar", 256),
}
LAUNCHER_FG = "otter_m3_launcher_foreground.png"
LAUNCHER_DENSITIES = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}
MONO_SVG = "otter_m3_monochrome_head.svg"


def verify_masters() -> list[str]:
    errors = []
    expected = {}
    for manifest in ("manifest.json", "manifest.m3-additions.json"):
        for a in json.loads((SRC / manifest).read_text())["assets"]:
            name = Path(a["file"]).name
            if name in expected and expected[name] != a["sha256"]:
                errors.append(f"{name}: manifests disagree")
            expected[name] = a["sha256"]
    for name, sha in sorted(expected.items()):
        p = SRC / "assets" / name
        if not p.exists():
            errors.append(f"{name}: missing")
        elif hashlib.sha256(p.read_bytes()).hexdigest() != sha:
            errors.append(f"{name}: SHA-256 mismatch (masters must stay unchanged)")
    return errors


def clean_alpha(img: Image.Image) -> Image.Image:
    r, g, b, a = img.convert("RGBA").split()
    a = a.point(lambda v: 0 if v < 16 else (255 if v >= 250 else v))
    return Image.merge("RGBA", (r, g, b, a))


def resize(img: Image.Image, px: int) -> Image.Image:
    # premultiplied, so transparent pixels' colour never bleeds into the edges
    return img.convert("RGBa").resize((px, px), Image.LANCZOS).convert("RGBA")


def zero_faint(img: Image.Image) -> Image.Image:
    r, g, b, a = img.split()
    return Image.merge("RGBA", (r, g, b, a.point(lambda v: 0 if v < 16 else v)))


def webp_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, "WEBP", lossless=True, quality=100, method=6, exact=False)
    return buf.getvalue()


def png_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def monochrome_vector() -> bytes:
    svg = (SRC / "assets" / MONO_SVG).read_text()
    path = re.search(r'\sd="([^"]+)"', svg).group(1)
    if 'translate(15.36 15.36) scale(0.97)' not in svg or 'evenodd' not in svg:
        raise SystemExit("monochrome SVG changed shape: update the transform/fill rule in export-assets.py")
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/export-assets.py from design/source-assets/assets/{MONO_SVG}; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="1024"
    android:viewportHeight="1024">
    <group
        android:translateX="15.36"
        android:translateY="15.36"
        android:scaleX="0.97"
        android:scaleY="0.97">
        <path
            android:fillColor="#FFFFFFFF"
            android:fillType="evenOdd"
            android:pathData="{path}" />
    </group>
</vector>
""".encode()


def path_points(path: str) -> list[tuple[float, float]]:
    """Absolute coordinates of an SVG path (M/L/C/Q/A/Z only; arcs contribute their end points, radii/flags skipped)."""
    pts = []
    for cmd, args in re.findall(r'([A-Za-z])([^A-Za-z]*)', path):
        nums = [float(n) for n in re.findall(r'-?\d+(?:\.\d+)?', args)]
        if cmd in "MLCQ":
            pts += list(zip(nums[0::2], nums[1::2]))
        elif cmd == "A":
            pts += [(nums[i + 5], nums[i + 6]) for i in range(0, len(nums), 7)]
        elif cmd != "Z":
            raise SystemExit(f"monochrome SVG uses path command {cmd!r}: extend path_points() in export-assets.py")
    return pts


def notification_vector() -> bytes:
    """Status-bar icon (D62): the monochrome head cropped to its bounds for a 24 dp viewport (masters untouched).

    Bounds come from the path's points (Bezier control points included, so the box can only be slightly larger than
    the shape); about 4 % padding on each side.
    """
    svg = (SRC / "assets" / MONO_SVG).read_text()
    path = re.search(r'\sd="([^"]+)"', svg).group(1)
    pts = path_points(path)
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    side = max(x1 - x0, y1 - y0) * 1.08
    tx, ty = -(x0 - (side - (x1 - x0)) / 2), -(y0 - (side - (y1 - y0)) / 2)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/export-assets.py from design/source-assets/assets/{MONO_SVG}; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{side:.1f}"
    android:viewportHeight="{side:.1f}">
    <group
        android:translateX="{tx:.1f}"
        android:translateY="{ty:.1f}">
        <path
            android:fillColor="#FFFFFFFF"
            android:fillType="evenOdd"
            android:pathData="{path}" />
    </group>
</vector>
""".encode()


def outputs() -> dict[Path, tuple[str, object]]:
    """Path -> (kind, payload). Images are compared by pixels, text byte for byte."""
    out = {}
    for master, (name, px) in ILLUSTRATIONS.items():
        img = zero_faint(resize(clean_alpha(Image.open(SRC / "assets" / master)), px))
        out[UI_RES / "drawable-nodpi" / f"{name}.webp"] = ("image", img)
    fg = Image.open(SRC / "assets" / LAUNCHER_FG).convert("RGBA")
    for density, px in LAUNCHER_DENSITIES.items():
        out[APP_RES / f"mipmap-{density}" / "ic_launcher_foreground.png"] = ("image", resize(fg, px))
    out[APP_RES / "drawable" / "ic_launcher_monochrome.xml"] = ("text", monochrome_vector())
    out[APP_RES / "drawable" / "ic_stat_otter.xml"] = ("text", notification_vector())
    return out


def same_pixels(path: Path, img: Image.Image) -> bool:
    try:
        on_disk = Image.open(path).convert("RGBA")
    except Exception:
        return False
    if on_disk.size != img.size:
        return False
    # lossless formats: compare visible pixels (RGB of fully transparent pixels does not matter)
    a, b = on_disk.load(), img.load()
    w, h = img.size
    for y in range(h):
        for x in range(w):
            p, q = a[x, y], b[x, y]
            if p[3] != q[3] or (q[3] and p[:3] != q[:3]):
                return False
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify masters and that outputs are up to date; write nothing")
    args = ap.parse_args()

    errors = verify_masters()
    if errors:
        print("masters:", *errors, sep="\n  ", file=sys.stderr)
        return 1
    stale = []
    webp_total = 0
    for path, (kind, payload) in outputs().items():
        rel = path.relative_to(ROOT)
        if args.check:
            ok = path.exists() and (path.read_bytes() == payload if kind == "text" else same_pixels(path, payload))
            if not ok:
                stale.append(str(rel))
            continue
        data = payload if kind == "text" else (webp_bytes(payload) if path.suffix == ".webp" else png_bytes(payload))
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
        if path.suffix == ".webp":
            webp_total += len(data)
        print(f"{len(data):>9,} B  {rel}")
    if args.check:
        if stale:
            print("outdated or missing outputs (run scripts/export-assets.py):", *stale, sep="\n  ", file=sys.stderr)
            return 1
        print("masters verified; all outputs up to date")
        return 0
    print(f"{webp_total:>9,} B  total of the {len(ILLUSTRATIONS)} WebP drawables (expected < 400 KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
